// Report factory — the last mile between "finding on the board" and
// "submission package ready to file".
//
// verify.ts confirms a finding 2/2 and bounty.ts drafts the raw report.
// What still leaks value: the assembled package needs a per-program impact
// narrative, the PoC as an artifact file, a scope/sensitivity check, and a
// pre-submit checklist — done by hand, done slowly, sometimes skipped.
//
// buildReportPackage() takes a VerificationReport + the bounty draft path and
// writes reports/packages/<addr>-<ts>/ containing:
//   SUBMISSION.md   — impact narrative + evidence summary + checklist
//   poc.test.sol    — the Foundry PoC (rendered from the probe technique)
//   evidence.json   — machine-readable verification record
//
// Read-only over the chain; writes land under reports/ only. The package is
// an ARTIFACT for the operator to review and submit — nothing is ever sent
// anywhere by this code.
import { mkdirSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { REPORT_DIR } from "./config.ts";
import { logEvent, upsertWatch } from "./bus.ts";

interface VerificationLike {
  address: string;
  chainId: string;
  technique: string;
  confirmed: boolean;
  attempts: Array<{ ok: boolean; profitWei: string; blockNumber?: string; forkRpc?: string; error?: string }>;
  bountyPath?: string;
  verifiedAt: number;
  note?: string;
}

/** Per-technique impact narrative seeds — the operator edits, but never
 * starts from a blank page. */
const IMPACT_SEEDS: Record<string, string> = {
  "side-entrance-reentrancy": "A flash-loan-funded attacker re-entered the deposit/withdraw pair through the contract's own callback, withdrawing other depositors' principal while the shares accounting briefly showed a healthy balance. Funds at risk: the full contract balance at the block of the PoC.",
  "erc4626-share-inflation": "A first-depositor share-price manipulation lets an attacker inflate the share price and donate-inflate round results, directly stealing value from subsequent depositors via rounded share math. Any depositor after the attacker's front-run loses up to their full deposit.",
  "oracle-spot-price": "The protocol prices assets from an AMM spot reserve, which a single large flash-loan-backed trade can move within one transaction. The PoC shows the manipulated price leading to over-payment/under-collateralization inside the same block.",
  "flash-arbitrary-call": "A flash-loan-funded arbitrary call passes attacker-chosen calldata to a contract that assumes the caller is trusted, enabling configuration change / fund movement in one transaction.",
  "unauthorized-mint": "A publicly callable mint entry point without effective access control lets anyone inflate supply at zero cost — direct theft from holders via dilution, or free collateral for later manipulation.",
};

const SCOPE_HINTS: Array<{ re: RegExp; note: string }> = [
  { re: /4626|vault|yearn|morpho/i, note: "ERC-4626 vaults are in scope for most major programs — check 'Vaults' or 'Yield' section." },
  { re: /aave|compound|lending|cdp/i, note: "Lending markets: confirm whether the pool itself is in scope or only peripheral contracts." },
  { re: /lz|layerzero|bridge/i, note: "Bridge/cross-chain programs usually require the exploit to work end-to-end across chains — note if the PoC is single-chain." },
];

export interface ReportPackage {
  dir: string;
  submissionPath: string;
  pocPath: string | null;
  evidencePath: string;
}

/** Render a Foundry PoC artifact for the technique, when the lab has a
 * template for it. Returns null when no template applies (the narrative
 * still ships, referencing the verification record instead). */
function renderPoc(v: VerificationLike): string | null {
  const addr = v.address;
  const header = `// SPDX-License-Identifier: UNLICENSED
pragma solidity ^0.8.20;

import "forge-std/Test.sol";

/// PoC for ${addr} — technique: ${v.technique}
/// Generated by the exploit-lab pipeline; reproduced ${v.attempts.filter((a) => a.ok).length}/${v.attempts.length} on independent forks.
contract PocTest is Test {
    address constant TARGET = ${addr};

    function setUp() public {
        // Fork the affected chain at the verified block:
        //   vm.createSelectFork(vm.envString("RPC_URL"), ${v.attempts[0]?.blockNumber ?? "latest"});
    }

    function test exploit() public pure {
        // Technique: ${v.technique}
        // Profit observed: ${v.attempts[0]?.profitWei ?? "0"} wei
        assertTrue(false, "fill the exploit path from the harness: reports/INCIDENT-*.md / probe harness");
    }
}`;
  return header.replace("function test exploit()", "function test_exploit()");
}

/** Assemble the package. Never throws: failures are logged and the partial
 * result returned. */
export function buildReportPackage(v: VerificationLike, program?: string): ReportPackage | null {
  if (!v.confirmed) return null;
  const ts = new Date(v.verifiedAt).toISOString().replace(/[:.]/g, "-").slice(0, 19);
  const dir = join(REPORT_DIR, "packages", `${v.address.slice(0, 10)}-${ts}`);
  try {
    mkdirSync(dir, { recursive: true });

    const profit = v.attempts[0]?.profitWei ?? "0";
    const impactSeed = IMPACT_SEEDS[v.technique] ?? "Impact: direct loss of user funds (see PoC and verification record).";
    const scopeNotes = SCOPE_HINTS.filter((h) => h.re.test(v.technique + " " + v.address)).map((h) => `- ${h.note}`);
    const bountyName = v.bountyPath && existsSync(v.bountyPath) ? readFileSync(v.bountyPath, "utf8").slice(0, 4_000) : "";

    const submission = [
      "# BOUNTY SUBMISSION — draft package",
      "",
      `_assembled ${new Date().toISOString()} — ${program ?? "program TBD"}_`,
      "",
      "## Summary",
      "",
      `Confirmed exploit on \`${v.address}\` (chain ${v.chainId}), technique **${v.technique}**.`,
      `Reproduced ${v.attempts.filter((a) => a.ok).length}/${v.attempts.length} on independent archive forks, profit up to **${BigInt(profit).toString()} wei** per run.`,
      "",
      "## Impact",
      "",
      impactSeed,
      "",
      "## Evidence",
      "",
      `- verification record: evidence.json (attempts, fork sources, block heads)`,
      v.bountyPath ? `- raw draft: ${v.bountyPath}` : "",
      bountyName ? "- raw draft excerpt below\n\n<details><summary>draft</summary>\n\n```\n" + bountyName.slice(0, 1200) + "\n```\n</details>" : "",
      "",
      "## Scope check",
      "",
      scopeNotes.length ? scopeNotes.join("\n") : "- confirm this contract is in the program's scope list before submitting.",
      "",
      "## Pre-submit checklist",
      "",
      "- [ ] Contract is in program scope",
      "- [ ] Impact tier matches program's severity table",
      "- [ ] PoC runs against mainnet fork at the recorded block",
      "- [ ] No live-chain interaction was performed or is implied",
      "- [ ] Contact/preference fields filled",
      "",
    ].filter((l) => l !== "").join("\n");

    writeFileSync(join(dir, "SUBMISSION.md"), submission);

    const poc = renderPoc(v);
    if (poc) writeFileSync(join(dir, "Poc.test.sol"), poc);

    const evidencePath = join(dir, "evidence.json");
    writeFileSync(evidencePath, JSON.stringify({ ...v, assembledAt: Date.now(), program: program ?? null }, null, 2));

    upsertWatch({ address: v.address, lastResult: `report package ready: ${dir}` });
    logEvent("daemon", `report package assembled: ${dir}`);
    return { dir, submissionPath: join(dir, "SUBMISSION.md"), pocPath: poc ? join(dir, "Poc.test.sol") : null, evidencePath };
  } catch (e) {
    logEvent("daemon", `report package failed (continuing): ${(e as Error).message}`);
    return null;
  }
}
