// Bug-bounty report generator: turns a fork-mode finding into a submission
// draft. This is the ONLY artifact a live-pool finding produces — evidence
// for responsible disclosure, not an exploit payload for a drain.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPORT_DIR, BOUNTY_PAYOUT_ADDRESS, payoutAddressValid } from "./config.ts";
import { isActionableFinding, isProductionTarget } from "./findings.ts";
import type { ForkFinding, PoolRecon } from "./fork.ts";

export function writeBountyReport(recon: PoolRecon, finding: ForkFinding, rpcName: string): string {
  if (!isProductionTarget(recon.chainId, recon.address)) {
    throw new Error(`refusing bounty draft: chain ${recon.chainId} / ${recon.address} is not a production target`);
  }
  if (!isActionableFinding(finding)) {
    throw new Error(`refusing bounty draft: finding is not actionable (${finding.notes.slice(0, 120)})`);
  }
  if (!payoutAddressValid()) {
    throw new Error(`BOUNTY_PAYOUT_ADDRESS is not a valid address: "${BOUNTY_PAYOUT_ADDRESS}"`);
  }
  mkdirSync(REPORT_DIR, { recursive: true });
  const slug = `${finding.technique}-${recon.address.slice(0, 12)}-${Date.now()}`;
  const path = join(REPORT_DIR, `bounty-draft-${slug}.md`);

  const profit = BigInt(finding.profitWei || "0");
  const impact =
    finding.simulated && profit > 0
      ? `The probe extracted ${profit} wei of the simulated stake in local fork simulation. ` +
        `This demonstrates the technique class applies at the interface level; the extractable amount ` +
        `scales with attacker capital and pool state and must be sized by manual analysis before any impact claim.`
      : `The technique probe applies at the interface level; impact must be confirmed by manual analysis.`;

  const content = `# Bug Bounty Report (DRAFT — auto-generated by the exploit-lab agent)

> ⚠️ Submit this through the project's official bug-bounty program
> (Immunefi, Code4rena, Sherlock, or the protocol's security@ contact).
> Do NOT attempt to execute this against live contracts — that is theft,
> regardless of technical possibility.

## Summary
- **Target pool:** ${recon.address} (chain ${recon.chainId}, RPC: ${rpcName})
- **Detected interface shape:** ${recon.shape}
- **Detected entrypoints:** ${recon.selectors.join(", ") || "none recognized"}
- **Technique hypothesis:** ${finding.technique}
- **Simulated locally:** ${finding.simulated ? "yes" : "no"}
- **Estimated impact:** ${finding.profitWei !== "0" ? `${finding.profitWei} wei on the probe's simulated stake (not a full-pool figure)` : "unquantified"}
- **Researcher payout address (for the bounty reward):** \`${BOUNTY_PAYOUT_ADDRESS}\`

## Reproduction (local fork only)
\`\`\`
anvil --fork-url <REMOTE_RPC>   # read-only fork
forge script <generated sim> --fork-url http://127.0.0.1:8545
\`\`\`
${finding.notes}

## Impact
${impact}

## Recommended remediation
- For reentrancy-class findings: apply checks-effects-interactions; verify
  accounting against internal credits, not raw balances; add a reentrancy guard.
- Validate that flash-loan callbacks cannot mutate depositor state mid-loan.

## Discloser checklist
- [ ] Identify the project's bounty program and scope rules
- [ ] Include block number / tx evidence from the local fork
- [ ] Never disclose publicly before the program's response window
`;

  writeFileSync(path, content);
  return path;
}
